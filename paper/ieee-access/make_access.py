"""Generate paper/ieee-access/main.tex (IEEE Access template) from paper/jstars/main.tex (IEEEtran journal).

The JSTARS file is the single source of the text: this script only swaps the front matter (template, author block,
abstract and keyword environments) and the biography block, so the two versions never drift apart.

    python paper/ieee-access/make_access.py
"""

from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "jstars" / "main.tex"
OUT = HERE / "main.tex"

FRONT = r"""\documentclass{ieeeaccess}
\usepackage{cite}
\usepackage{amsmath,amssymb,amsfonts}
\usepackage{graphicx}
\usepackage{textcomp}
\usepackage{booktabs}
\usepackage{array}
\newcolumntype{L}[1]{>{\raggedright\arraybackslash}p{#1}}
\usepackage{url}
\graphicspath{{../jstars/}}
\makeatletter\ifdefined\xfigwd\else\newdimen\xfigwd\fi\makeatother %% used by the Access caption code

\begin{document}
\history{Date of publication xxxx 00, 0000, date of current version xxxx 00, 0000.}
\doi{10.1109/ACCESS.2026.DOI}

\title{%(title)s}

\author{\uppercase{Thinuka Lehan}\authorrefmark{1} and \uppercase{Achala Aponsu}\authorrefmark{1}}
\address[1]{Informatics Institute of Technology (IIT), Colombo, Sri Lanka}
\tfootnote{This research received no specific grant from any funding agency in the public, commercial, or not-for-profit sectors.}

\markboth
{T. Lehan and A. Aponsu: DamageSAR-Bench: Building-Level Evaluation of Frozen Foundation Models}
{T. Lehan and A. Aponsu: DamageSAR-Bench: Building-Level Evaluation of Frozen Foundation Models}

\corresp{Corresponding author: Thinuka Lehan (e-mail: thinukalehanfyp@gmail.com).}

\begin{abstract}
%(abstract)s
\end{abstract}

\begin{keywords}
%(keywords)s
\end{keywords}

\titlepgskip=-21pt

\maketitle
"""


def between(s: str, a: str, b: str) -> str:
    i = s.index(a) + len(a)
    return s[i:s.index(b, i)].strip()


def main() -> None:
    s = SRC.read_text(encoding="utf-8")
    title = between(s, "\\title{", "}\n")
    abstract = between(s, "\\begin{abstract}", "\\end{abstract}")
    keywords = between(s, "\\begin{IEEEkeywords}", "\\end{IEEEkeywords}")
    body = s[s.index("\\end{IEEEkeywords}") + len("\\end{IEEEkeywords}"):]
    body = body.replace("\\IEEEPARstart", "\\PARstart")
    # Access biographies take a photo; until photos exist, a framed placeholder of the required size (1 x 1.25 in)
    body = re.sub(r"\\begin\{IEEEbiographynophoto\}\{([^}]*)\}",
                  lambda m: "\\begin{IEEEbiography}[{\\framebox[1in][c]{\\rule{0pt}{1.25in}Photo}}]{" + m.group(1) + "}",
                  body)
    body = body.replace("\\end{IEEEbiographynophoto}", "\\end{IEEEbiography}")
    # Access ends with \EOD after the biographies
    body = body.replace("\\end{document}", "\\EOD\n\n\\end{document}")
    body = re.sub(r"\\bibliographystyle\{IEEEtran\}", r"\\bibliographystyle{IEEEtran}", body)
    body = body.replace("\\bibliography{refs}", "\\bibliography{../jstars/refs}")
    out = FRONT % {"title": title, "abstract": abstract, "keywords": keywords} + body
    header = ("% GENERATED by make_access.py from ../jstars/main.tex: edit the JSTARS file, then rerun the script.\n")
    OUT.write_text(header + out, encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
